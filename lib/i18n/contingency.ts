const COPY: Record<Lang, Copy> = { en, hi, mr };

/** Translate a planner key with {param} interpolation (falls back to English). */
export function tc(lang: Lang, key: ContingencyKey, params?: Record<string, string | number>): string {
  const template = COPY[lang][key] ?? en[key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, n: string) => (params[n] !== undefined ? String(params[n]) : `{${n}}`));
}
