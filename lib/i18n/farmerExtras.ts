const EXTRA: Record<Lang, ExtraCopy> = { en, hi, mr };

/** Translate an extra key with {param} interpolation. */
export function tx(lang: Lang, key: ExtraKey, params?: Record<string, string | number>): string {
  const template = EXTRA[lang][key] ?? en[key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => (params[name] !== undefined ? String(params[name]) : `{${name}}`));
}
